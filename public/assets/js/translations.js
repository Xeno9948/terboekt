function interpolateTranslation(str, vars) {
    if (!str) return str;
    const data = vars || window.TerboektSiteVars || {};
    return String(str).replace(/\{(\w+)\}/g, (match, key) => (
        data[key] != null && data[key] !== '' ? String(data[key]) : match
    ));
}

function applyTranslations(lang) {
    const dict = translations[lang] || translations.nl;
    document.querySelectorAll('[data-i18n]').forEach((el) => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) el.textContent = interpolateTranslation(dict[key]);
    });
    if (typeof window.paintSiteFields === 'function') {
        window.paintSiteFields();
    }
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (dict[key]) el.setAttribute('placeholder', dict[key]);
    });
    document.querySelectorAll('.lang-switcher a').forEach((link) => {
        link.classList.toggle('active', link.getAttribute('data-lang') === lang);
        link.setAttribute('aria-current', link.getAttribute('data-lang') === lang ? 'true' : 'false');
    });
    document.documentElement.lang = lang;
}

function setLanguage(lang) {
    currentLang = lang;
    window.currentLang = lang;
    localStorage.setItem('lang', lang);
    applyTranslations(lang);
    document.dispatchEvent(new CustomEvent('lang:changed', { detail: lang }));
}

function bindLanguageSwitcher() {
    document.querySelectorAll('.lang-switcher a').forEach((link) => {
        if (link.dataset.bound === '1') return;
        link.dataset.bound = '1';
        link.addEventListener('click', (e) => {
            e.preventDefault();
            setLanguage(link.getAttribute('data-lang'));
        });
    });
}

function bootTranslations() {
    bindLanguageSwitcher();
    applyTranslations(currentLang);
}

document.addEventListener('DOMContentLoaded', bootTranslations);
document.addEventListener('components:ready', bootTranslations);
if (document.readyState !== 'loading') {
    bootTranslations();
}

